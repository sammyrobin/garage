<?php

declare(strict_types=1);

/**
 * Writes app/config.php from environment variables (GitHub Actions secrets).
 *   php bin/build-config.php
 *
 * - Values are read from the environment, never from arguments (so they are not
 *   visible in process lists) and never printed.
 * - ADMIN_PASSWORD is stored only as password_hash(); the plain text is discarded.
 * - Fails (exit 1) if any required variable is missing, naming only the variable.
 */

if (PHP_SAPI !== 'cli') {
    exit(1);
}

$required = [
    'APP_URL', 'APP_KEY', 'DB_NAME', 'DB_USER', 'DB_PASS', 'ADMIN_PASSWORD', 'MIGRATE_TOKEN', 'SMTP_PASSWORD',
];
$optional = ['DB_HOST', 'ADMIN_EMAIL', 'CPANEL_HOST', 'CPANEL_USER', 'CPANEL_API_TOKEN', 'SMTP_HOST', 'SMTP_PORT', 'SMTP_USER'];

$env = [];
$missing = [];
foreach ([...$required, ...$optional] as $name) {
    $value = getenv($name);
    $env[$name] = $value === false ? '' : (string) $value;
    if ($env[$name] === '' && in_array($name, $required, true)) {
        $missing[] = $name;
    }
}
if ($missing) {
    fwrite(STDERR, 'Missing required secrets: ' . implode(', ', $missing) . "\n");
    exit(1);
}
if (strlen($env['MIGRATE_TOKEN']) < 32 || strlen($env['APP_KEY']) < 32) {
    fwrite(STDERR, "MIGRATE_TOKEN and APP_KEY must be at least 32 characters.\n");
    exit(1);
}

$url = rtrim($env['APP_URL'], '/');
$config = [
    'app' => [
        'env' => 'production',
        'url' => $url,
        'base_path' => rtrim((string) parse_url($url, PHP_URL_PATH), '/'),
        'key' => $env['APP_KEY'],
        'timezone' => 'America/Mexico_City',
    ],
    'db' => [
        'host' => $env['DB_HOST'] ?: 'localhost',
        'port' => 3306,
        'name' => $env['DB_NAME'],
        'user' => $env['DB_USER'],
        'pass' => $env['DB_PASS'],
        'charset' => 'utf8mb4',
    ],
    'admin' => [
        'password_hash' => password_hash($env['ADMIN_PASSWORD'], PASSWORD_DEFAULT),
        'session_ttl' => 1800,
        'max_attempts' => 5,
        'attempt_window' => 900,
    ],
    'session' => ['secure' => true],
    'migrate_token' => $env['MIGRATE_TOKEN'],
    'mail' => [
        'host' => $env['SMTP_HOST'] ?: 'localhost',
        'port' => (int) ($env['SMTP_PORT'] ?: 587),
        'secure' => 'tls',
        'verify_tls' => false,
        'username' => $env['SMTP_USER'] ?: 'contacto@samueltorres.dev',
        'password' => $env['SMTP_PASSWORD'],
        'from_email' => 'contacto@samueltorres.dev',
        'from_name' => 'GARAGE',
        'notify_to' => $env['ADMIN_EMAIL'] ?: 'samuelt@conqr.mx',
    ],
    'cpanel' => [
        'host' => $env['CPANEL_HOST'],
        'user' => $env['CPANEL_USER'],
        'token' => $env['CPANEL_API_TOKEN'],
        // The account is called on its own server, whose certificate may not match the host.
        'verify_tls' => false,
    ],
];

$target = dirname(__DIR__) . '/app/config.php';
$php = "<?php\n\n// Generated by bin/build-config.php during deploy. Do not edit or commit.\n\nreturn " . var_export($config, true) . ";\n";
if (file_put_contents($target, $php, LOCK_EX) === false) {
    fwrite(STDERR, "Could not write app/config.php\n");
    exit(1);
}
echo "app/config.php generated (" . count($config) . " sections).\n";
